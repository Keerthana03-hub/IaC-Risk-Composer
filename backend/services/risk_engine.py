"""
services/risk_engine.py
------------------------
Risk Assessment and Scoring Engine for IaC Risk Composer (Step 4).

Consumes threat findings generated by Step 3 and computes:
  - Qualitative Likelihood score (1 to 5)
  - Impact score (1 to 5)
  - Inherent Risk Score (Likelihood × Impact, 1 to 25)
  - Inherent Risk Level (Low, Medium, High, Critical)
  - Confidence-Adjusted Risk Score
  - Assessment Status (Assessed vs. Provisional)
  - Explanations and comprehensive analysis Risk Summary
"""

from __future__ import annotations

from typing import Any

# ---------------------------------------------------------------------------
# Constants and Matrices
# ---------------------------------------------------------------------------

# 5x5 Impact Mapping based on threat severity
SEVERITY_TO_IMPACT: dict[str, int] = {
    "critical": 5,   # Severe: potential large-scale compromise / critical impact
    "high": 4,       # Major: significant data exposure or service disruption
    "medium": 3,     # Moderate: meaningful disruption or limited exposure
    "low": 2,        # Minor: limited impact affecting small component
    "negligible": 1, # Negligible: minimal security impact
    "info": 1,
}

# Confidence Multipliers
CONFIDENCE_FACTORS: dict[str, float] = {
    "high": 1.00,
    "medium": 0.75,
    "low": 0.50,
}

# Qualitative labels for Likelihood & Impact scales (1-5)
LIKELIHOOD_LABELS: dict[int, str] = {
    1: "Rare",
    2: "Unlikely",
    3: "Possible",
    4: "Likely",
    5: "Almost Certain",
}

IMPACT_LABELS: dict[int, str] = {
    1: "Negligible",
    2: "Minor",
    3: "Moderate",
    4: "Major",
    5: "Severe",
}

# Risk Level Ordering for determining overall risk level
RISK_LEVEL_ORDER: list[str] = ["Low", "Medium", "High", "Critical"]


# ---------------------------------------------------------------------------
# Scoring Formulas & Core Helpers
# ---------------------------------------------------------------------------


def calculate_inherent_risk(likelihood: int, impact: int) -> int:
    """
    Calculate Inherent Risk Score = Likelihood × Impact.

    Args:
        likelihood: Integer score between 1 and 5.
        impact: Integer score between 1 and 5.

    Returns:
        Integer score between 1 and 25.
    """
    if not (1 <= likelihood <= 5):
        raise ValueError(f"Likelihood must be between 1 and 5, got {likelihood}")
    if not (1 <= impact <= 5):
        raise ValueError(f"Impact must be between 1 and 5, got {impact}")
    return likelihood * impact


def get_risk_level(inherent_score: int | None) -> str | None:
    """
    Map an inherent risk score (1–25) to its risk level band:
      1–4:   Low
      5–9:   Medium
      10–16: High
      17–25: Critical

    Returns:
        Risk level string or None if inherent_score is None.
    """
    if inherent_score is None:
        return None
    if 1 <= inherent_score <= 4:
        return "Low"
    if 5 <= inherent_score <= 9:
        return "Medium"
    if 10 <= inherent_score <= 16:
        return "High"
    if 17 <= inherent_score <= 25:
        return "Critical"
    raise ValueError(f"Inherent score must be between 1 and 25, got {inherent_score}")


def get_confidence_factor(confidence: str | None) -> float:
    """
    Map qualitative confidence to deterministic factor:
      High   = 1.00
      Medium = 0.75
      Low    = 0.50
    """
    if not confidence:
        return 1.00
    return CONFIDENCE_FACTORS.get(str(confidence).strip().lower(), 1.00)


def calculate_confidence_adjusted_score(
    inherent_score: int | None,
    confidence_factor: float | None,
) -> float | None:
    """
    Calculate Confidence-Adjusted Score = Inherent Score × Confidence Factor.
    Rounded to 2 decimal places.
    """
    if inherent_score is None or confidence_factor is None:
        return None
    return round(inherent_score * confidence_factor, 2)


def map_severity_to_impact(severity: str | None) -> int | None:
    """Map finding severity string to 1-5 Impact scale."""
    if not severity:
        return None
    return SEVERITY_TO_IMPACT.get(str(severity).strip().lower(), None)


def determine_likelihood(finding: dict[str, Any]) -> int | None:
    """
    Deterministically assign a qualitative Likelihood score (1-5) based on
    finding metadata, threat category, evidence, and exposure scope.
    """
    threat_id = finding.get("threat_id", "")
    title = str(finding.get("title", "")).lower()
    evidence = finding.get("evidence", {}) or {}

    # Threat 3: Unrestricted access to all ports
    if threat_id == "THREAT-003" and ("all ports" in title or evidence.get("exposed_scope") == "all_ports"):
        return 5  # Almost Certain: entire port range open to 0.0.0.0/0

    # Threat 1: S3 Public Access
    if threat_id == "THREAT-001":
        acl = str(evidence.get("acl", "")).lower()
        if acl == "public-read-write":
            return 5  # Almost Certain: anonymous write access allows trivial exploitation
        return 4      # Likely: anonymous read access directly available to public internet

    # Threat 2: Unrestricted SSH Access
    if threat_id == "THREAT-002":
        return 4      # Likely: port 22 exposed directly to public internet, constantly scanned

    # Threat 3: Unrestricted sensitive database/admin ports (RDP, MySQL, Postgres, Redis, Mongo)
    if threat_id == "THREAT-003":
        return 4      # Likely: sensitive service port exposed directly to public internet

    # Threat 4: Publicly accessible database
    if threat_id == "THREAT-004":
        return 4      # Likely: database assigned public IP reachable over internet

    # Threat 6: Overly permissive IAM wildcard (* on *)
    if threat_id == "THREAT-006":
        return 4      # Likely: broad admin policy enables immediate account-wide actions

    # Threat 5: Storage encryption explicitly disabled
    if threat_id == "THREAT-005":
        return 2      # Unlikely: requires physical disk or unauthorized backup/snapshot access

    # ── CloudFormation Specific Likelihoods ──────────────────────────────
    if threat_id == "CFN-001":
        acl_str = str(evidence.get("AccessControl", "")).lower()
        if "write" in acl_str:
            return 5  # Almost Certain: anonymous write access
        return 4      # Likely: public read access

    if threat_id in ("CFN-003", "CFN-004"):
        return 4      # Likely: direct wildcard admin or internet-accessible security group

    if threat_id == "CFN-005":
        return 2      # Unlikely: requires unauthorized disk snapshot/volume access

    if threat_id == "CFN-006":
        if evidence.get("AuthType") == "NONE":
            return 4  # Likely: unauthenticated public internet endpoint
        return 3      # Possible: missing active tracing

    # ── Kubernetes Specific Likelihoods ──────────────────────────────────
    if threat_id in ("K8S-001", "K8S-002", "K8S-005", "K8S-009"):
        return 4      # Likely: privileged pod, root user, host namespaces, or wildcard RBAC

    if threat_id == "K8S-004":
        dangerous = evidence.get("dangerous_capabilities", [])
        if any(cap in ("SYS_ADMIN", "SYS_MODULE") for cap in dangerous):
            return 4  # Likely: near-root capabilities
        return 3      # Possible: other elevated capabilities

    if threat_id in ("K8S-003", "K8S-006", "K8S-007", "K8S-008", "K8S-010", "K8S-012"):
        return 3      # Possible: conditional exploitability or posture weakness

    # General fallback based on severity if custom threat
    severity = str(finding.get("severity", "")).lower()
    if severity in ("critical", "high"):
        return 4
    if severity == "medium":
        return 3
    if severity == "low":
        return 2

    return None


# ---------------------------------------------------------------------------
# Single Finding Risk Assessment
# ---------------------------------------------------------------------------


def assess_finding(finding: dict[str, Any]) -> dict[str, Any]:
    """
    Perform deterministic risk scoring on a single threat finding.

    Returns:
        A nested risk assessment dictionary adhering to the Step 4 schema.
    """
    detection_status = str(finding.get("detection_status", "")).strip()
    raw_severity = finding.get("severity")
    confidence_str = finding.get("confidence")

    # Handle Needs Review findings:
    # Needs Review findings represent unconfirmed or incomplete configurations.
    # We do not present them as confirmed vulnerabilities or fabricate scores.
    if detection_status == "Needs Review":
        confidence_factor = get_confidence_factor(confidence_str)
        return {
            "likelihood": None,
            "impact": None,
            "inherent_risk_score": None,
            "risk_level": None,
            "confidence_factor": confidence_factor,
            "confidence_adjusted_score": None,
            "assessment_status": "Provisional",
            "scoring_explanation": (
                "Provisional finding: configuration is unconfirmed or requires review. "
                "Inherent risk cannot be determined without verifying environment context or account defaults."
            ),
            "scoring_method": "Likelihood × Impact",
        }

    # For Confirmed findings:
    impact = map_severity_to_impact(raw_severity)
    if impact is None:
        # Severity is missing or unknown
        confidence_factor = get_confidence_factor(confidence_str)
        return {
            "likelihood": None,
            "impact": None,
            "inherent_risk_score": None,
            "risk_level": None,
            "confidence_factor": confidence_factor,
            "confidence_adjusted_score": None,
            "assessment_status": "Provisional",
            "scoring_explanation": f"Cannot calculate inherent risk score: severity '{raw_severity}' is missing or unknown.",
            "scoring_method": "Likelihood × Impact",
        }

    likelihood = determine_likelihood(finding)
    if likelihood is None:
        confidence_factor = get_confidence_factor(confidence_str)
        return {
            "likelihood": None,
            "impact": impact,
            "inherent_risk_score": None,
            "risk_level": None,
            "confidence_factor": confidence_factor,
            "confidence_adjusted_score": None,
            "assessment_status": "Provisional",
            "scoring_explanation": "Likelihood could not be determined from available evidence.",
            "scoring_method": "Likelihood × Impact",
        }

    inherent_score = calculate_inherent_risk(likelihood, impact)
    risk_level = get_risk_level(inherent_score)
    confidence_factor = get_confidence_factor(confidence_str)
    adjusted_score = calculate_confidence_adjusted_score(inherent_score, confidence_factor)

    l_label = LIKELIHOOD_LABELS.get(likelihood, str(likelihood))
    i_label = IMPACT_LABELS.get(impact, str(impact))

    scoring_explanation = (
        f"Likelihood assessed as {likelihood} ({l_label}) based on exposure context; "
        f"Impact assessed as {impact} ({i_label}) based on {raw_severity} severity. "
        f"Inherent Risk Score: {likelihood} × {impact} = {inherent_score} ({risk_level})."
    )

    return {
        "likelihood": likelihood,
        "impact": impact,
        "inherent_risk_score": inherent_score,
        "risk_level": risk_level,
        "confidence_factor": confidence_factor,
        "confidence_adjusted_score": adjusted_score,
        "assessment_status": "Assessed",
        "scoring_explanation": scoring_explanation,
        "scoring_method": "Likelihood × Impact",
    }


# ---------------------------------------------------------------------------
# Risk Summary Calculation
# ---------------------------------------------------------------------------


def calculate_risk_summary(assessed_findings: list[dict[str, Any]]) -> dict[str, Any]:
    """
    Calculate aggregate risk posture metrics across all findings.

    Returns:
        Dictionary adhering to the risk_summary schema.
    """
    total = len(assessed_findings)
    confirmed = 0
    needs_review = 0
    low_count = 0
    med_count = 0
    high_count = 0
    crit_count = 0

    highest_score: int | None = None
    highest_level_index = -1

    for f in assessed_findings:
        status = f.get("detection_status", "")
        if status == "Confirmed":
            confirmed += 1
        elif status == "Needs Review":
            needs_review += 1

        assessment = f.get("risk_assessment") or {}
        level = assessment.get("risk_level")
        score = assessment.get("inherent_risk_score")

        if level == "Low":
            low_count += 1
        elif level == "Medium":
            med_count += 1
        elif level == "High":
            high_count += 1
        elif level == "Critical":
            crit_count += 1

        if score is not None:
            if highest_score is None or score > highest_score:
                highest_score = score

        if level in RISK_LEVEL_ORDER:
            idx = RISK_LEVEL_ORDER.index(level)
            if idx > highest_level_index:
                highest_level_index = idx

    overall_level = (
        RISK_LEVEL_ORDER[highest_level_index]
        if highest_level_index >= 0
        else "Not Assessed"
    )

    return {
        "total_findings": total,
        "confirmed_findings": confirmed,
        "needs_review_findings": needs_review,
        "low_risk_count": low_count,
        "medium_risk_count": med_count,
        "high_risk_count": high_count,
        "critical_risk_count": crit_count,
        "highest_inherent_risk_score": highest_score,
        "overall_risk_level": overall_level,
    }


# ---------------------------------------------------------------------------
# Main Public Pipeline Function
# ---------------------------------------------------------------------------


def assess_risks(
    threat_findings: list[dict[str, Any]],
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """
    Orchestrate risk assessment across all threat findings.

    Args:
        threat_findings: List of finding dicts from Step 3 threat engine.

    Returns:
        (assessed_findings, risk_summary)
    """
    if not threat_findings:
        return [], calculate_risk_summary([])

    assessed: list[dict[str, Any]] = []
    for item in threat_findings:
        finding_copy = dict(item)
        finding_copy["risk_assessment"] = assess_finding(finding_copy)
        assessed.append(finding_copy)

    summary = calculate_risk_summary(assessed)
    return assessed, summary
