class NumberedCanvas(canvas.Canvas):
    """
    Two-pass canvas that writes dynamic 'Page X of Y' footers
    and running headers across all pages.
    """

    def __init__(self, *args: Any, **kwargs: Any) -> None:
        super().__init__(*args, **kwargs)
        self._saved_page_states: list[dict[str, Any]] = []

    def showPage(self) -> None:
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self) -> None:
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int) -> None:
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(COLOR_MUTED)

        # Running header (pages 2 and later)
        if self._pageNumber > 1:
            self.drawString(
                36,
                PAGE_HEIGHT - 32,
                "IaC Risk Composer — Infrastructure Security Assessment Report",
            )
            self.setStrokeColor(COLOR_BORDER)
            self.setLineWidth(0.5)
            self.line(36, PAGE_HEIGHT - 36, PAGE_WIDTH - 36, PAGE_HEIGHT - 36)

        # Running footer (all pages)
        self.setStrokeColor(COLOR_BORDER)
        self.setLineWidth(0.5)
        self.line(36, 42, PAGE_WIDTH - 36, 42)

        self.drawString(
            36,
            30,
            "CONFIDENTIAL — Generated by IaC Risk Composer (Static Analysis Only)",
        )
        page_str = f"Page {self._pageNumber} of {total_pages}"
        self.drawRightString(PAGE_WIDTH - 36, 30, page_str)
        self.restoreState()


