def generate_pdf_report(analysis_data: Any) -> bytes:
    """
    Generate a complete PDF security assessment report from analysis results.

    Args:
        analysis_data: Pydantic TerraformAnalysisResponse or dictionary
                       containing Steps 1-6 analysis output.

    Returns:
        bytes: Raw PDF file bytes starting with b'%PDF'.
    """
    # Normalize input into dictionary
    if hasattr(analysis_data, "model_dump"):
        data = analysis_data.model_dump()
    elif isinstance(analysis_data, dict):
        data = analysis_data
    else:
        data = {}

    filename = str(data.get("filename") or "infrastructure.tf")
    resource_count = int(data.get("resource_count") or 0)
    resource_types = list(data.get("resource_types") or [])
    resources = list(data.get("resources") or [])
    infra_map = data.get("infrastructure_map") or {}
    threat_findings = list(data.get("threat_findings") or [])
    risk_summary = data.get("risk_summary") or {}
    risk_explanations = list(data.get("risk_explanations") or [])
    remediations = list(data.get("remediations") or [])

    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        leftMargin=36,
        rightMargin=36,
        topMargin=46,
        bottomMargin=48,
    )

    # Styles
    base_styles = getSampleStyleSheet()

    style_title = ParagraphStyle(
        "DocTitle",
        parent=base_styles["Title"],
        fontName="Helvetica-Bold",
        fontSize=22,
        leading=26,
        textColor=COLOR_PRIMARY,
        alignment=0,
    )
    style_subtitle = ParagraphStyle(
        "DocSubtitle",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=12,
        leading=16,
        textColor=COLOR_MUTED,
    )
    style_h1 = ParagraphStyle(
        "SecHeading1",
        parent=base_styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=14,
        leading=18,
        textColor=COLOR_PRIMARY,
        spaceBefore=14,
        spaceAfter=8,
        keepWithNext=True,
    )
    style_h2 = ParagraphStyle(
        "SecHeading2",
        parent=base_styles["Heading2"],
        fontName="Helvetica-Bold",
        fontSize=11,
        leading=15,
        textColor=COLOR_SECONDARY,
        spaceBefore=10,
        spaceAfter=4,
        keepWithNext=True,
    )
    style_body = ParagraphStyle(
        "DocBody",
        parent=base_styles["Normal"],
        fontName="Helvetica",
        fontSize=9,
        leading=13,
        textColor=COLOR_PRIMARY,
    )
    style_body_muted = ParagraphStyle(
        "DocBodyMuted",
        parent=style_body,
        textColor=COLOR_MUTED,
    )
    style_callout = ParagraphStyle(
        "DocCallout",
        parent=style_body,
        fontSize=8.5,
        leading=12,
        textColor=COLOR_PRIMARY,
    )
    style_code = ParagraphStyle(
        "DocCode",
        fontName="Courier",
        fontSize=7.5,
        leading=10,
        textColor=COLOR_PRIMARY,
    )

    elements: list[Any] = []

    # -----------------------------------------------------------------------
    # Section 1: Report Cover & Header
    # -----------------------------------------------------------------------
    elements.append(Paragraph("IaC Risk Composer", style_title))
    elements.append(
        Paragraph(
            "Infrastructure-as-Code Security Assessment Report",
            style_subtitle,
        )
    )
    elements.append(Spacer(1, 8))

    # Metadata Summary Grid
    now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    meta_rows = [
        [
            Paragraph("<b>Target File:</b>", style_body),
            Paragraph(f"<font name='Courier'>{_esc(filename)}</font>", style_body),
            Paragraph("<b>Assessment Date:</b>", style_body),
            Paragraph(_esc(now_utc), style_body),
        ],
        [
            Paragraph("<b>Analyzed Resources:</b>", style_body),
            Paragraph(str(resource_count), style_body),
            Paragraph("<b>Assessment Scope:</b>", style_body),
            Paragraph("Static IaC (HCL2 AST)", style_body),
        ],
    ]
    meta_table = Table(meta_rows, colWidths=[110, 160, 110, 160])
    meta_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    elements.append(meta_table)
    elements.append(Spacer(1, 8))

    # Scope Notice Callout
    scope_notice = (
        "<b>Notice:</b> This security assessment is based exclusively on static analysis of the declared "
        "Terraform (.tf) source code. It does not inspect live cloud environments, active IAM credentials, "
        "or runtime network connectivity. Missing explicit configuration does not automatically establish "
        "a live vulnerability if account-level defaults protect the workload."
    )
    notice_table = Table(
        [[Paragraph(scope_notice, style_callout)]],
        colWidths=[USABLE_WIDTH],
    )
    notice_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor("#eff6ff")),  # Blue 50
                ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#bfdbfe")),  # Blue 200
                ("TOPPADDING", (0, 0), (-1, -1), 6),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
            ]
        )
    )
    elements.append(notice_table)
    elements.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # Section 2: Executive Summary
    # -----------------------------------------------------------------------
    elements.append(Paragraph("1. Executive Summary", style_h1))
    elements.append(
        HRFlowable(
            width="100%", thickness=1, color=COLOR_BORDER, spaceAfter=8, spaceBefore=2
        )
    )

    overall_level = risk_summary.get("overall_risk_level") or (
        "Not Assessed" if not threat_findings else "Assessed"
    )
    level_color = _get_level_color(overall_level)

    total_findings_count = len(threat_findings)
    confirmed_count = risk_summary.get("confirmed_findings")
    needs_review_count = risk_summary.get("needs_review_findings")
    if confirmed_count is None:
        confirmed_count = sum(
            1 for f in threat_findings if f.get("detection_status") == "Confirmed"
        )
    if needs_review_count is None:
        needs_review_count = sum(
            1 for f in threat_findings if f.get("detection_status") == "Needs Review"
        )

    crit_count = risk_summary.get("critical_risk_count", 0)
    high_count = risk_summary.get("high_risk_count", 0)
    med_count = risk_summary.get("medium_risk_count", 0)
    low_count = risk_summary.get("low_risk_count", 0)

    exec_table_data = [
        [
            Paragraph("<b>Overall Posture:</b>", style_body),
            Paragraph(
                f"<b><font color='{level_color.hexval()}'>{_esc(overall_level).upper()}</font></b>",
                style_body,
            ),
            Paragraph("<b>Total Findings:</b>", style_body),
            Paragraph(f"<b>{total_findings_count}</b>", style_body),
        ],
        [
            Paragraph("<b>Confirmed Findings:</b>", style_body),
            Paragraph(str(confirmed_count), style_body),
            Paragraph("<b>Needs Review Findings:</b>", style_body),
            Paragraph(str(needs_review_count), style_body),
        ],
        [
            Paragraph("<b>Critical Risk Count:</b>", style_body),
            Paragraph(
                f"<font color='{COLOR_CRITICAL.hexval()}'>{crit_count}</font>",
                style_body,
            ),
            Paragraph("<b>High Risk Count:</b>", style_body),
            Paragraph(
                f"<font color='{COLOR_HIGH.hexval()}'>{high_count}</font>",
                style_body,
            ),
        ],
        [
            Paragraph("<b>Medium Risk Count:</b>", style_body),
            Paragraph(
                f"<font color='{COLOR_MEDIUM.hexval()}'>{med_count}</font>",
                style_body,
            ),
            Paragraph("<b>Low Risk Count:</b>", style_body),
            Paragraph(
                f"<font color='{COLOR_LOW.hexval()}'>{low_count}</font>",
                style_body,
            ),
        ],
    ]

    exec_table = Table(exec_table_data, colWidths=[130, 140, 140, 130])
    exec_table.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ]
        )
    )
    elements.append(exec_table)
    elements.append(Spacer(1, 8))

    # Notes on Provisional / Needs Review
    if needs_review_count > 0:
        provisional_note = (
            f"<b>Status Clarification:</b> {needs_review_count} finding(s) are designated as "
            "<b>Needs Review</b> or <b>Provisional</b>. These represent configurations with partial "
            "attributes or potential conditional logic that cannot be definitively confirmed without "
            "architectural validation. They are strictly non-final and must not be treated as verified vulnerabilities."
        )
        elements.append(Paragraph(provisional_note, style_body_muted))
        elements.append(Spacer(1, 8))

    # -----------------------------------------------------------------------
    # Section 3: Infrastructure Overview
    # -----------------------------------------------------------------------
    elements.append(Paragraph("2. Infrastructure Overview", style_h1))
    elements.append(
        HRFlowable(
            width="100%", thickness=1, color=COLOR_BORDER, spaceAfter=8, spaceBefore=2
        )
    )

    if not resources:
        elements.append(
            Paragraph(
                "No resource declarations were identified in the uploaded Terraform configuration.",
                style_body_muted,
            )
        )
    else:
        res_rows: list[list[Any]] = [
            [
                Paragraph("<b>Resource Type</b>", style_body),
                Paragraph("<b>Resource Name</b>", style_body),
                Paragraph("<b>Full Identifier</b>", style_body),
            ]
        ]
        for r in resources:
            r_type = r.get("type", "unknown")
            r_name = r.get("name", "unknown")
            res_rows.append(
                [
                    Paragraph(f"<font name='Courier'>{_esc(r_type)}</font>", style_body),
                    Paragraph(_esc(r_name), style_body),
                    Paragraph(
                        f"<font name='Courier'>{_esc(r_type)}.{_esc(r_name)}</font>",
                        style_body,
                    ),
                ]
            )

        res_table = Table(res_rows, colWidths=[180, 160, 200])
        res_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_LIGHT),
                    ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ]
            )
        )
        elements.append(res_table)

    elements.append(Spacer(1, 6))

    # Infrastructure Map Edges (Topology)
    edges = infra_map.get("edges") or []
    nodes = infra_map.get("nodes") or []
    topo_summary = (
        f"<b>Graph Topology:</b> {len(nodes)} mapped node(s), {len(edges)} detected inter-resource edge(s)."
    )
    elements.append(Paragraph(topo_summary, style_body))

    if edges:
        edge_rows: list[list[Any]] = [
            [
                Paragraph("<b>Source Resource</b>", style_body),
                Paragraph("<b>Relationship</b>", style_body),
                Paragraph("<b>Referenced Target</b>", style_body),
            ]
        ]
        for e in edges:
            edge_rows.append(
                [
                    Paragraph(f"<font name='Courier'>{_esc(e.get('source'))}</font>", style_body),
                    Paragraph(_esc(e.get("relationship", "references")), style_body),
                    Paragraph(f"<font name='Courier'>{_esc(e.get('target'))}</font>", style_body),
                ]
            )
        edge_table = Table(edge_rows, colWidths=[200, 140, 200])
        edge_table.setStyle(
            TableStyle(
                [
                    ("BACKGROUND", (0, 0), (-1, 0), COLOR_BG_LIGHT),
                    ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                    ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                    ("TOPPADDING", (0, 0), (-1, -1), 3),
                    ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                ]
            )
        )
        elements.append(Spacer(1, 4))
        elements.append(edge_table)
    else:
        elements.append(
            Paragraph(
                "<i>No explicit inter-resource relationships (edges) detected among parsed resources.</i>",
                style_body_muted,
            )
        )

    elements.append(Spacer(1, 10))

    # -----------------------------------------------------------------------
    # Section 4: Threat Findings
    # -----------------------------------------------------------------------
    elements.append(Paragraph("3. Detected Threat Findings", style_h1))
    elements.append(
        HRFlowable(
            width="100%", thickness=1, color=COLOR_BORDER, spaceAfter=8, spaceBefore=2
        )
    )

    if not threat_findings:
        elements.append(
            Paragraph(
                "✅ <b>Clean Posture:</b> No security misconfigurations or policy violations were detected "
                "based on active threat detection templates.",
                style_body,
            )
        )
        elements.append(Spacer(1, 8))
    else:
        for idx, f in enumerate(threat_findings, start=1):
            finding_id = f.get("finding_id", f"finding-{idx}")
            threat_id = f.get("threat_id", "THREAT-UNKNOWN")
            title = f.get("title", "Security Misconfiguration")
            res_id = f.get("affected_resource_id", "unknown")
            severity = f.get("severity", "Medium")
            det_status = f.get("detection_status", "Unconfirmed")
            confidence = f.get("confidence", "Medium")
            impact = f.get("impact", "")
            rec = f.get("recommendation", "")
            evidence = f.get("evidence") or {}
            risk_ass = f.get("risk_assessment") or {}

            sev_color = _get_level_color(severity)
            header_text = (
                f"<b>Finding {idx}: {html.escape(title)}</b> "
                f"(<font color='{sev_color.hexval()}'><b>{_esc(severity)}</b></font> | "
                f"Status: <b>{_esc(det_status)}</b>)"
            )

            # Format evidence safely
            if isinstance(evidence, dict) and evidence:
                ev_str = ", ".join(f"<b>{k}:</b> {_esc(v)}" for k, v in evidence.items())
            else:
                ev_str = _esc(evidence) if evidence else "None recorded"

            # Risk Assessment rows
            inh_score = risk_ass.get("inherent_risk_score")
            risk_lvl = risk_ass.get("risk_level")
            likelihood = risk_ass.get("likelihood")
            imp_val = risk_ass.get("impact")
            ass_status = risk_ass.get("assessment_status", "Not Assessed")
            scoring_exp = risk_ass.get("scoring_explanation", "")

            if inh_score is not None:
                risk_summary_text = (
                    f"<b>Inherent Score:</b> {inh_score} ({_esc(risk_lvl)}) | "
                    f"<b>Likelihood:</b> {likelihood}/5 | <b>Impact:</b> {imp_val}/5 | "
                    f"<b>Status:</b> {_esc(ass_status)}"
                )
            else:
                risk_summary_text = f"<b>Risk Score:</b> Not Assessed | <b>Status:</b> {_esc(ass_status)}"

            f_table_data = [
                [
                    Paragraph("<b>Finding & Threat ID:</b>", style_body),
                    Paragraph(f"<font name='Courier'>{_esc(finding_id)}</font> ({_esc(threat_id)})", style_body),
                ],
                [
                    Paragraph("<b>Target Resource:</b>", style_body),
                    Paragraph(f"<font name='Courier'>{_esc(res_id)}</font>", style_body),
                ],
                [
                    Paragraph("<b>Risk & Confidence:</b>", style_body),
                    Paragraph(f"{risk_summary_text} | <b>Confidence:</b> {_esc(confidence)}", style_body),
                ],
                [
                    Paragraph("<b>Evidence:</b>", style_body),
                    Paragraph(ev_str, style_body),
                ],
                [
                    Paragraph("<b>Security Impact:</b>", style_body),
                    Paragraph(_esc(impact), style_body),
                ],
                [
                    Paragraph("<b>Recommendation:</b>", style_body),
                    Paragraph(_esc(rec), style_body),
                ],
            ]

            if scoring_exp:
                f_table_data.append(
                    [
                        Paragraph("<b>Scoring Rationale:</b>", style_body),
                        Paragraph(_esc(scoring_exp), style_body_muted),
                    ]
                )

            f_table = Table(f_table_data, colWidths=[130, 410])
            f_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                        ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ]
                )
            )

            finding_flowables: list[Any] = [
                Paragraph(header_text, style_h2),
                Spacer(1, 2),
                f_table,
                Spacer(1, 8),
            ]
            elements.append(KeepTogether(finding_flowables))

    elements.append(Spacer(1, 6))

    # -----------------------------------------------------------------------
    # Section 5: Risk Explanations
    # -----------------------------------------------------------------------
    elements.append(Paragraph("4. Plain-Language Risk Explanations", style_h1))
    elements.append(
        HRFlowable(
            width="100%", thickness=1, color=COLOR_BORDER, spaceAfter=8, spaceBefore=2
        )
    )

    if not risk_explanations:
        elements.append(
            Paragraph("No risk explanations generated for this analysis.", style_body_muted)
        )
    else:
        for idx, exp in enumerate(risk_explanations, start=1):
            exp_finding_id = exp.get("finding_id", f"finding-{idx}")
            summary = exp.get("summary", "")
            why = exp.get("why_it_matters", "")
            ev_exp = exp.get("evidence_explanation", "")
            uncertainty = exp.get("uncertainty", "")
            rec_actions = exp.get("recommended_actions") or []
            verif_steps = exp.get("verification_steps") or []
            exp_status = exp.get("explanation_status", "Generated")
            exp_method = exp.get("explanation_method", "rule_based")

            exp_rows = [
                [
                    Paragraph("<b>Finding Reference:</b>", style_body),
                    Paragraph(f"<font name='Courier'>{_esc(exp_finding_id)}</font>", style_body),
                ],
                [
                    Paragraph("<b>Summary:</b>", style_body),
                    Paragraph(_esc(summary), style_body),
                ],
                [
                    Paragraph("<b>Why It Matters:</b>", style_body),
                    Paragraph(_esc(why), style_body),
                ],
                [
                    Paragraph("<b>Evidence Rationale:</b>", style_body),
                    Paragraph(_esc(ev_exp), style_body),
                ],
                [
                    Paragraph("<b>Uncertainty & Assumptions:</b>", style_body),
                    Paragraph(f"<i>{_esc(uncertainty)}</i>", style_body),
                ],
            ]

            if rec_actions:
                actions_html = "<br/>".join(f"• {_esc(a)}" for a in rec_actions)
                exp_rows.append(
                    [
                        Paragraph("<b>Recommended Actions:</b>", style_body),
                        Paragraph(actions_html, style_body),
                    ]
                )

            if verif_steps:
                verif_html = "<br/>".join(f"• {_esc(v)}" for v in verif_steps)
                exp_rows.append(
                    [
                        Paragraph("<b>Verification Steps:</b>", style_body),
                        Paragraph(verif_html, style_body),
                    ]
                )

            exp_rows.append(
                [
                    Paragraph("<b>Engine Method:</b>", style_body),
                    Paragraph(
                        f"Status: {_esc(exp_status)} | Engine: <b>{_esc(exp_method)}</b> "
                        "(Deterministic Rule-Based Explainer, No External LLM)",
                        style_body_muted,
                    ),
                ]
            )

            exp_table = Table(exp_rows, colWidths=[140, 400])
            exp_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                        ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ]
                )
            )

            exp_flowables: list[Any] = [
                Paragraph(f"<b>Explanation {idx}: {_esc(exp_finding_id)}</b>", style_h2),
                Spacer(1, 2),
                exp_table,
                Spacer(1, 8),
            ]
            elements.append(KeepTogether(exp_flowables))

    elements.append(Spacer(1, 6))

    # -----------------------------------------------------------------------
    # Section 6: Remediation Recommendations & Safe Code Fixes
    # -----------------------------------------------------------------------
    elements.append(
        Paragraph("5. Remediation Recommendations & Safe Fixes", style_h1)
    )
    elements.append(
        HRFlowable(
            width="100%", thickness=1, color=COLOR_BORDER, spaceAfter=8, spaceBefore=2
        )
    )

    if not remediations:
        elements.append(
            Paragraph(
                "No remediation recommendations generated for this analysis.",
                style_body_muted,
            )
        )
    else:
        for idx, rem in enumerate(remediations, start=1):
            rem_id = rem.get("remediation_id", f"rem-{idx}")
            finding_ref = rem.get("finding_id", "")
            title = rem.get("title", "Remediation Recommendation")
            res_id = rem.get("affected_resource_id", "")
            rem_status = rem.get("remediation_status", "Suggested")
            patch_type = rem.get("patch_type", "manual")
            explanation = rem.get("explanation", "")
            actions = rem.get("recommended_actions") or []
            suggested_code = rem.get("suggested_code")
            assumptions = rem.get("assumptions") or []
            validation = rem.get("validation_steps") or []

            rem_rows: list[list[Any]] = [
                [
                    Paragraph("<b>Remediation ID:</b>", style_body),
                    Paragraph(f"<font name='Courier'>{_esc(rem_id)}</font>", style_body),
                ],
                [
                    Paragraph("<b>Target Resource:</b>", style_body),
                    Paragraph(f"<font name='Courier'>{_esc(res_id)}</font>", style_body),
                ],
                [
                    Paragraph("<b>Status & Patch Type:</b>", style_body),
                    Paragraph(
                        f"Status: <b>{_esc(rem_status)}</b> | Patch Type: <b>{_esc(patch_type)}</b> "
                        "(Suggestion Only — Requires Developer Review)",
                        style_body,
                    ),
                ],
                [
                    Paragraph("<b>Remediation Guidance:</b>", style_body),
                    Paragraph(_esc(explanation), style_body),
                ],
            ]

            if actions:
                actions_html = "<br/>".join(f"• {_esc(a)}" for a in actions)
                rem_rows.append(
                    [
                        Paragraph("<b>Action Items:</b>", style_body),
                        Paragraph(actions_html, style_body),
                    ]
                )

            if assumptions:
                assumptions_html = "<br/>".join(f"• {_esc(a)}" for a in assumptions)
                rem_rows.append(
                    [
                        Paragraph("<b>Assumptions:</b>", style_body),
                        Paragraph(assumptions_html, style_body_muted),
                    ]
                )

            if validation:
                val_html = "<br/>".join(f"• {_esc(v)}" for v in validation)
                rem_rows.append(
                    [
                        Paragraph("<b>Validation Steps:</b>", style_body),
                        Paragraph(val_html, style_body),
                    ]
                )

            rem_table = Table(rem_rows, colWidths=[140, 400])
            rem_table.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_LIGHT),
                        ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                        ("INNERGRID", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                    ]
                )
            )

            rem_flowables: list[Any] = [
                Paragraph(f"<b>Remediation {idx}: {_esc(title)}</b>", style_h2),
                Spacer(1, 2),
                rem_table,
            ]

            # If suggested Terraform code is available, format in a dedicated monospaced box
            if suggested_code:
                code_notice = (
                    "<b>⚠️ Suggested Terraform Fix (Review Before Applying — Not Automatically Executed):</b>"
                )
                rem_flowables.append(Spacer(1, 4))
                rem_flowables.append(Paragraph(code_notice, style_callout))
                rem_flowables.append(Spacer(1, 2))

                clean_code = str(suggested_code).strip()
                code_box = Table(
                    [[Preformatted(clean_code, style_code)]],
                    colWidths=[USABLE_WIDTH],
                )
                code_box.setStyle(
                    TableStyle(
                        [
                            ("BACKGROUND", (0, 0), (-1, -1), COLOR_BG_CODE),
                            ("BOX", (0, 0), (-1, -1), 0.5, COLOR_BORDER),
                            ("TOPPADDING", (0, 0), (-1, -1), 4),
                            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
                            ("LEFTPADDING", (0, 0), (-1, -1), 6),
                            ("RIGHTPADDING", (0, 0), (-1, -1), 6),
                        ]
                    )
                )
                rem_flowables.append(code_box)
            else:
                manual_notice = (
                    "<i>ℹ Automated code patch omitted for safety. Follow manual remediation action items above.</i>"
                )
                rem_flowables.append(Spacer(1, 3))
                rem_flowables.append(Paragraph(manual_notice, style_body_muted))

            rem_flowables.append(Spacer(1, 8))
            elements.append(KeepTogether(rem_flowables))

    elements.append(Spacer(1, 6))

    # -----------------------------------------------------------------------
    # Section 7: Limitations and Security Disclaimer
    # -----------------------------------------------------------------------
    disclaimer_elements: list[Any] = [
        Paragraph("6. Limitations and Security Disclaimer", style_h1),
        HRFlowable(
            width="100%", thickness=1, color=COLOR_BORDER, spaceAfter=8, spaceBefore=2
        ),
        Paragraph(
            "<b>1. Static Analysis Scope:</b> This report evaluates declared syntax and resource attributes "
            "within the uploaded Terraform (.tf) file. It does not inspect external remote state, live cloud "
            "account configurations, runtime IAM permissions, or network routing.",
            style_body,
        ),
        Spacer(1, 4),
        Paragraph(
            "<b>2. Runtime Guardrails vs. Code Findings:</b> Missing explicit configurations (e.g. bucket encryption) "
            "do not prove that deployed assets are unencrypted at runtime. Cloud provider account defaults, "
            "AWS Organizations Service Control Policies (SCPs), or centralized KMS settings may enforce encryption.",
            style_body,
        ),
        Spacer(1, 4),
        Paragraph(
            "<b>3. Non-Destructive Advisory:</b> All suggested code patches and remediation actions are advisory "
            "proposals requiring security architecture review. IaC Risk Composer never modifies user repositories "
            "or deploys cloud resources.",
            style_body,
        ),
        Spacer(1, 4),
        Paragraph(
            "<b>4. No Live External LLM:</b> Risk assessments, explanations, and remediations were generated via "
            "deterministic rule-based engines.",
            style_body,
        ),
    ]
    elements.append(KeepTogether(disclaimer_elements))

    # Build PDF with dynamic NumberedCanvas
    doc.build(elements, canvasmaker=NumberedCanvas)

    return buffer.getvalue()
