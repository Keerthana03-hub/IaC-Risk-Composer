PAGE_WIDTH, PAGE_HEIGHT = letter
USABLE_WIDTH = PAGE_WIDTH - 72  # 36pt margins on each side = 540pt

COLOR_PRIMARY = colors.HexColor("#0f172a")  # Slate 900
COLOR_SECONDARY = colors.HexColor("#1e293b")  # Slate 800
COLOR_ACCENT = colors.HexColor("#0284c7")  # Sky 600
COLOR_MUTED = colors.HexColor("#64748b")  # Slate 500
COLOR_BORDER = colors.HexColor("#cbd5e1")  # Slate 300
COLOR_BG_LIGHT = colors.HexColor("#f8fafc")  # Slate 50
COLOR_BG_CODE = colors.HexColor("#f1f5f9")  # Slate 100

COLOR_CRITICAL = colors.HexColor("#b91c1c")  # Red 700
COLOR_HIGH = colors.HexColor("#dc2626")  # Red 600
COLOR_MEDIUM = colors.HexColor("#d97706")  # Amber 600
COLOR_LOW = colors.HexColor("#15803d")  # Green 700
COLOR_NEUTRAL = colors.HexColor("#475569")  # Slate 600


def _get_level_color(level: str | None) -> colors.HexColor:
    """Map risk level string to theme color."""
    lvl = (level or "").strip().lower()
    if "crit" in lvl:
        return COLOR_CRITICAL
    if "high" in lvl:
        return COLOR_HIGH
    if "med" in lvl:
        return COLOR_MEDIUM
    if "low" in lvl:
        return COLOR_LOW
    return COLOR_NEUTRAL


def _esc(val: Any) -> str:
    """HTML-escape raw values to prevent XML parsing syntax errors in ReportLab."""
    if val is None:
        return "—"
    return html.escape(str(val))


