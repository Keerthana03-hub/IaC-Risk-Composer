"""
services/report_generator.py
----------------------------
PDF Security Assessment Report Generation Service (Step 7).

Generates a professional, downloadable security assessment report in PDF format
using ReportLab from the structured results produced by Steps 1–6:
- Infrastructure overview (Step 1 & 2)
- Detected threat findings (Step 3)
- Inherent & adjusted risk scores and summary (Step 4)
- Evidence-grounded plain-language explanations (Step 5)
- Actionable remediation recommendations and safe code patches (Step 6)

Safety & Governance Principles:
-------------------------------
1. Read-only / Non-destructive: Never modifies user files or executes Terraform.
2. Grounded & Transparent: Never invents risk scores, findings, or relationships.
3. Status Integrity: Preserves 'Needs Review', 'Provisional', and 'Not Assessed'.
   Never labels suggested fixes as applied or provisional findings as confirmed.
4. Stateless & Secure: Generates PDF entirely in-memory using BytesIO, avoiding
   temporary file storage and path traversal risks.
"""

